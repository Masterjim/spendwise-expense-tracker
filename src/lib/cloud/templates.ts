import { CATEGORIES, type Expense } from "@/types/expense";
import { formatCurrency, formatDate, formatMonthLabel, monthKey, toISODate } from "@/lib/format";
import { csvRows } from "./csv";
import type { ExportTemplate, TemplateContext, TemplateId } from "./types";

const round2 = (n: number) => Math.round(n * 100) / 100;
const sum = (xs: Expense[]) => round2(xs.reduce((a, e) => a + e.amount, 0));
const byDate = (a: Expense, b: Expense) => a.date.localeCompare(b.date);
const stamp = (now: Date) => toISODate(now);

function monthRange(now: Date, offset = 0) {
  const start = new Date(now.getFullYear(), now.getMonth() + offset, 1);
  const end = offset === 0 ? now : new Date(now.getFullYear(), now.getMonth() + offset + 1, 0);
  return { start: toISODate(start), end: toISODate(end) };
}

function inRange(e: Expense, start: string, end: string) {
  return e.date >= start && e.date <= end;
}

const fullBackup: ExportTemplate = {
  id: "full-backup",
  name: "Full Backup",
  description: "Every expense with IDs and timestamps. Restore-ready and machine-readable.",
  audience: "Backups · Migrations",
  icon: "🛟",
  accent: "#4f46e5",
  formatLabel: "JSON",
  scope: () => "All time",
  select: (expenses) => [...expenses].sort(byDate),
  render: (records, { now }) => ({
    filename: `spendwise-backup-${stamp(now)}.json`,
    mimeType: "application/json",
    records: records.length,
    content: JSON.stringify(
      { schemaVersion: 1, generator: "Spendwise", generatedAt: now.toISOString(), currency: "USD", count: records.length, expenses: records },
      null,
      2,
    ),
  }),
};

const monthlySummary: ExportTemplate = {
  id: "monthly-summary",
  name: "Monthly Summary",
  description: "A readable digest of this month: totals, change vs. last month, categories and biggest purchases.",
  audience: "Personal review · Notion · Slack",
  icon: "🗓️",
  accent: "#0ea5e9",
  formatLabel: "Markdown",
  scope: ({ now }) => formatMonthLabel(monthKey(toISODate(now)), "long"),
  select: (expenses, { now }) => {
    const { start, end } = monthRange(now);
    return expenses.filter((e) => inRange(e, start, end)).sort(byDate);
  },
  render: (records, { now }) => {
    const month = formatMonthLabel(monthKey(toISODate(now)), "long");
    const total = sum(records);
    const cats = CATEGORIES.map((c) => ({ c, t: sum(records.filter((e) => e.category === c)), n: records.filter((e) => e.category === c).length }))
      .filter((x) => x.n > 0)
      .sort((a, b) => b.t - a.t);
    const top = [...records].sort((a, b) => b.amount - a.amount).slice(0, 5);
    const days = now.getDate();
    const lines = [
      `# ${month} — Spending Summary`,
      ``,
      `> Generated by Spendwise on ${formatDate(toISODate(now))}`,
      ``,
      `| Metric | Value |`,
      `| --- | ---: |`,
      `| Total spent | **${formatCurrency(total)}** |`,
      `| Transactions | ${records.length} |`,
      `| Daily average | ${formatCurrency(days ? total / days : 0)} |`,
      `| Top category | ${cats[0] ? `${cats[0].c} (${formatCurrency(cats[0].t)})` : "—"} |`,
      ``,
      `## By category`,
      ``,
      `| Category | Transactions | Total | Share |`,
      `| --- | ---: | ---: | ---: |`,
      ...cats.map((x) => `| ${x.c} | ${x.n} | ${formatCurrency(x.t)} | ${total ? ((x.t / total) * 100).toFixed(1) : "0.0"}% |`),
      ``,
      `## Largest expenses`,
      ``,
      ...top.map((e, i) => `${i + 1}. **${formatCurrency(e.amount)}** — ${e.description.replace(/[|*_`]/g, "")} _(${e.category}, ${formatDate(e.date)})_`),
      ``,
    ];
    return {
      filename: `spendwise-summary-${monthKey(toISODate(now))}.md`,
      mimeType: "text/markdown",
      records: records.length,
      content: lines.join("\n"),
    };
  },
};

const taxReport: ExportTemplate = {
  id: "tax-report",
  name: "Tax Report",
  description: "Year-to-date totals per category followed by an itemized ledger, grouped for your accountant.",
  audience: "Accountant · Tax season",
  icon: "🧾",
  accent: "#10b981",
  formatLabel: "CSV",
  scope: ({ now }) => `Jan 1 – ${formatDate(toISODate(now))}`,
  select: (expenses, { now }) => {
    const start = `${now.getFullYear()}-01-01`;
    const end = toISODate(now);
    return expenses
      .filter((e) => inRange(e, start, end))
      .sort((a, b) => CATEGORIES.indexOf(a.category) - CATEGORIES.indexOf(b.category) || byDate(a, b));
  },
  render: (records, { now }) => {
    const year = now.getFullYear();
    const rows: Array<Array<string | number>> = [
      [`Spendwise Tax Report ${year}`],
      [`Period`, `${year}-01-01 to ${toISODate(now)}`],
      [`Generated`, now.toISOString()],
      [`Note`, `Informational only. Confirm deductibility with a tax professional.`],
      [],
      [`Category`, `Transactions`, `Total (USD)`],
      ...CATEGORIES.map((c) => {
        const xs = records.filter((e) => e.category === c);
        return [c, xs.length, sum(xs).toFixed(2)];
      }),
      [`TOTAL`, records.length, sum(records).toFixed(2)],
      [],
      [`Date`, `Category`, `Description`, `Amount (USD)`],
      ...records.map((e) => [e.date, e.category, e.description, e.amount.toFixed(2)]),
    ];
    return { filename: `spendwise-tax-report-${year}.csv`, mimeType: "text/csv", records: records.length, content: "\uFEFF" + csvRows(rows) };
  },
};

const categoryAnalysis: ExportTemplate = {
  id: "category-analysis",
  name: "Category Analysis",
  description: "A category × month matrix for the last 6 months with averages, share and trend. Pivot-table ready.",
  audience: "Budgeting · Spreadsheets",
  icon: "📊",
  accent: "#f59e0b",
  formatLabel: "CSV",
  scope: ({ now }) => {
    const first = toISODate(new Date(now.getFullYear(), now.getMonth() - 5, 1));
    return `${formatMonthLabel(monthKey(first), "long")} – ${formatMonthLabel(monthKey(toISODate(now)), "long")}`;
  },
  select: (expenses, { now }) => {
    const start = toISODate(new Date(now.getFullYear(), now.getMonth() - 5, 1));
    return expenses.filter((e) => inRange(e, start, toISODate(now))).sort(byDate);
  },
  render: (records, { now }) => {
    const months = Array.from({ length: 6 }, (_, i) => monthKey(toISODate(new Date(now.getFullYear(), now.getMonth() - 5 + i, 1))));
    const total = sum(records);
    const header = ["Category", ...months.map((m) => formatMonthLabel(m, "long")), "Total", "Avg / month", "Avg / transaction", "Share", "Trend (last 3 vs prior 3)"];
    const rows = CATEGORIES.map((c) => {
      const xs = records.filter((e) => e.category === c);
      const perMonth = months.map((m) => sum(xs.filter((e) => monthKey(e.date) === m)));
      const prior = perMonth.slice(0, 3).reduce((a, b) => a + b, 0);
      const recent = perMonth.slice(3).reduce((a, b) => a + b, 0);
      const t = sum(xs);
      return [
        c,
        ...perMonth.map((v) => v.toFixed(2)),
        t.toFixed(2),
        (t / 6).toFixed(2),
        xs.length ? (t / xs.length).toFixed(2) : "0.00",
        total ? `${((t / total) * 100).toFixed(1)}%` : "0.0%",
        prior ? `${(((recent - prior) / prior) * 100).toFixed(1)}%` : recent ? "new" : "—",
      ];
    });
    const totals = ["TOTAL", ...months.map((m) => sum(records.filter((e) => monthKey(e.date) === m)).toFixed(2)), total.toFixed(2), (total / 6).toFixed(2), records.length ? (total / records.length).toFixed(2) : "0.00", "100.0%", ""];
    return {
      filename: `spendwise-category-analysis-${stamp(now)}.csv`,
      mimeType: "text/csv",
      records: records.length,
      content: "\uFEFF" + csvRows([header, ...rows, totals]),
    };
  },
};

export const TEMPLATES: Record<TemplateId, ExportTemplate> = {
  "full-backup": fullBackup,
  "monthly-summary": monthlySummary,
  "tax-report": taxReport,
  "category-analysis": categoryAnalysis,
};

export const TEMPLATE_LIST = Object.values(TEMPLATES);

export function renderTemplate(id: TemplateId, expenses: Expense[], ctx: TemplateContext = { now: new Date() }) {
  const template = TEMPLATES[id];
  return template.render(template.select(expenses, ctx), ctx);
}
